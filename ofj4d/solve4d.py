def vm_equiv_strain(eps):
    """von Mises equivalent strain from Voigt strain with engineering shears."""
    ex, ey, ez, gxy, gyz, gzx = eps.T
    tr = (ex+ey+ez)/3.0
    dx, dy, dz = ex-tr, ey-tr, ez-tr
    ee = dx*dx + dy*dy + dz*dz + 0.5*(gxy*gxy + gyz*gyz + gzx*gzx)
    return np.sqrt(np.maximum(2.0/3.0*ee, 0.0))


def pdl_secant_modulus(eps_eq):
    """Secant modulus of the bilinear curve
       sigma = E1*e                        e <= ek
       sigma = E1*ek + E2*(e-ek)           e >  ek
    """
    E1, E2, ek = spec.PDL_E1, spec.PDL_E2, spec.PDL_EPS_KNEE
    e = np.maximum(eps_eq, 1e-12)
    return np.where(e <= ek, E1, (E1*ek + E2*(e-ek))/e)


class Operators:
    """Element operators for one configuration (rebuilt when nodes move).

    With `reuse=True` the COO -> CSR mapping is built once and the per-iteration
    assembly becomes a scatter-add into a fixed pattern.  Only the per-element
    modulus changes between nonlinear iterations, so re-sorting 24M COO entries
    every time was ~4x the cost of the assembly itself.  Exact: the pattern is
    identical and values differ only by summation order (~1e-16 relative).
    """

    def __init__(self, nodes, tets, nu, reuse=False):
        G, V = shape_grads(nodes, tets)
        neg = V <= 0
        if neg.any():
            tets = tets.copy(); tets[neg] = tets[neg][:, [0, 1, 3, 2]]
            G, V = shape_grads(nodes, tets)
        self.tets = tets
        self.B = B_matrix(G)
        self.V = V
        self.Dhat = isotropic_D(1.0, nu)
        BD = np.einsum('nki,kl->nli', self.B, self.Dhat)          # Dhat B
        self.Ke_unit = np.einsum('nli,nlj->nij', BD, self.B)*V[:, None, None]
        del BD
        d = (3*tets[:, :, None] + np.arange(3)[None, None, :]).reshape(len(tets), 12)
        self.dofs = d
        self.rows = np.repeat(d, 12, axis=1).ravel().astype(np.int32)
        self.cols = np.tile(d, (1, 12)).ravel().astype(np.int32)
        self.reuse = reuse
        self._csr = None

    def _build_map(self, ndof):
        """Fixed CSR pattern + the COO -> CSR index map (~1.9 s for the PDL,
        amortised over the ~30 iterations of a solve)."""
        keys = self.rows.astype(np.int64)*ndof + self.cols
        uk, inv = np.unique(keys, return_inverse=True)
        del keys
        rows_u = (uk // ndof).astype(np.int32)
        cols_u = (uk % ndof).astype(np.int32)
        indptr = np.zeros(ndof+1, dtype=np.int64)
        np.cumsum(np.bincount(rows_u, minlength=ndof), out=indptr[1:])
        self._csr = (inv.astype(np.int32), cols_u, indptr, len(uk), ndof)

    def K(self, E, ndof):
        vals = (self.Ke_unit*np.asarray(E)[:, None, None]).ravel()
        if not self.reuse:
            return coo_matrix((vals, (self.rows, self.cols)),
                              shape=(ndof, ndof)).tocsr()
        if self._csr is None or self._csr[4] != ndof:
            self._build_map(ndof)
        inv, cols_u, indptr, nnz, _ = self._csr
        data = np.bincount(inv, weights=vals, minlength=nnz)
        return csr_matrix((data, cols_u, indptr), shape=(ndof, ndof))

    def strain(self, u):
        ue = u.reshape(-1, 3)[self.tets].reshape(len(self.tets), 12)
        return np.einsum('nij,nj->ni', self.B, ue)


def contact_ops(C):
    s, tri, w, n = C['slave'], C['tri'], C['bary'], C['normal']
    npair = len(s)
    dofs = np.concatenate(
        [3*s[:, None] + np.arange(3)[None, :],
         (3*tri[:, :, None] + np.arange(3)[None, None, :]).reshape(npair, 9)], axis=1)
    R = np.zeros((npair, 3, 12))
    for d in range(3):
        R[:, d, d] = 1.0
        for j in range(3):
            R[:, d, 3+3*j+d] = -w[:, j]
    a = np.einsum('nij,ni->nj', R, n)
    return dofs, R, a


def make_amg(A, B=None):
    """Energy-smoothed aggregation, falling back to cheaper setups under memory
    pressure -- an 8 h staging run must not die on one transient allocation."""
    import gc
    for smooth, coarse in (('energy', 1500), ('jacobi', 3000), (None, 6000)):
        try:
            return _amg(A, B, smooth, coarse)
        except (MemoryError, np.core._exceptions._ArrayMemoryError):
            gc.collect()
            print(f"    [amg] memory pressure -> falling back "
                  f"(smooth={smooth} failed)", flush=True)
    raise MemoryError('AMG setup failed at every fallback level')


def _amg(A, B, smooth, max_coarse):
    return pyamg.smoothed_aggregation_solver(
        A, B=B, max_coarse=max_coarse, smooth=smooth,
        strength=('symmetric', {'theta': 0.02}),
        presmoother=('gauss_seidel', {'sweep': 'symmetric', 'iterations': 2}),
        postsmoother=('gauss_seidel', {'sweep': 'symmetric', 'iterations': 2}))


class Pardiso:
    """MKL PARDISO on the reduced system, mtype 2 (real symmetric positive definite).

    The AMG hierarchy has to be rebuilt every iteration because the contact springs
    move the spectrum, and that setup is ~75% of the wall time.  A sparse direct
    factorisation has no such problem: the reduced system is SPD, 150k dof and only
    5.7M nnz, and the fill-in is modest (25M nnz in the factor, ~230 MB).

    PARDISO splits into three phases, and only the first depends on the VALUES not
    at all:
        11  symbolic analysis (fill-reducing ordering)   ~0.59 s -- pattern only
        22  numeric factorisation                        ~0.20 s
        33  back-substitution                            ~0.07 s
    The pattern changes only when the contact active set changes, so the analysis is
    kept and reused whenever the incoming pattern is unchanged (phases 22+33 alone).
    That is exact -- no tolerance, no stale-preconditioner risk, which is what made
    every AMG reuse scheme fail here.

    Only the upper triangle is passed, as mtype 2 requires.
    """

    name = 'pardiso'
    ANALYSIS, FACTORISE, SOLVE, REFACTORISE, FREE = 11, 22, 33, 23, -1

    def __init__(self):
        from pypardiso import PyPardisoSolver
        self.ps = PyPardisoSolver(mtype=2)
        self._ptr = None
        self._ind = None
        self.n_analysis = 0
        self.n_reuse = 0

    @staticmethod
    def available():
        if LINSOLVE == 'amg':
            return False
        try:
            import pypardiso                                   # noqa: F401
            return True
        except Exception as e:
            if LINSOLVE == 'pardiso':
                raise RuntimeError(f'OFJ_LINSOLVE=pardiso but pypardiso is unusable: {e}')
            return False

    def _phase(self, ph, U, b):
        self.ps.set_phase(ph)
        return self.ps._call_pardiso(U, b)

    def solve(self, As, bs, upper=False):
        """Returns (x, reused) for the SPD system As x = bs.

        `upper=True` says As is already the upper triangle.  The GPU assembler
        hands one over directly, in index arrays it reuses between iterations, so
        the pattern check below succeeds on identity and costs nothing.
        """
        U = As if upper else triu(As, format='csr')
        if not upper:
            U.sort_indices()
            if U.dtype != np.float64:
                U = U.astype(np.float64)
        b = np.ascontiguousarray(bs, dtype=np.float64)
        self.ps._check_A(U)
        reused = self._ptr is not None and (
            (self._ptr is U.indptr and self._ind is U.indices)
            or (len(self._ptr) == len(U.indptr)
                and len(self._ind) == len(U.indices)
                and np.array_equal(self._ptr, U.indptr)
                and np.array_equal(self._ind, U.indices)))
        try:
            if reused:
                x = self._phase(self.REFACTORISE, U, b)        # 22 + 33
                self.n_reuse += 1
            else:
                self._phase(self.ANALYSIS, U, b)
                self._phase(self.FACTORISE, U, b)
                x = self._phase(self.SOLVE, U, b)
                self._ptr, self._ind = U.indptr, U.indices
                self.n_analysis += 1
        except Exception:
            # a failed phase leaves the handle in an undefined state; drop it and
            # redo the analysis from scratch before giving up on the backend
            self.free()
            self.ps._check_A(U)
            self._phase(self.ANALYSIS, U, b)
            self._phase(self.FACTORISE, U, b)
            x = self._phase(self.SOLVE, U, b)
            self._ptr, self._ind = U.indptr, U.indices
            self.n_analysis += 1
            reused = False
        return x, reused

    def free(self):
        try:
            self.ps.free_memory(everything=True)
        except Exception:
            pass
        self._ptr = self._ind = None


