"""Stage D: one nonlinear solve of the 4D model configuration.

Two nonlinearities are resolved in a single outer loop:
  * unilateral contact between the aligner and the crowns/attachments, with
    Coulomb friction carried by a secant tangential stiffness;
  * the bilinear ('double linear stress-strain curve') PDL, applied as a secant
    modulus driven by the von Mises equivalent strain of each element.

Because D(E, nu) = E * Dhat(nu), the element operators B and V are built once per
configuration and only the per-element modulus is refreshed between iterations.
"""
